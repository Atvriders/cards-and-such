export function pickTarget(length: number, rng: () => number): string {
  const list = length === 4 ? TARGETS_4 : length === 5 ? TARGETS_5 : TARGETS_6;
  return list[Math.floor(rng() * list.length)]!;
}

export function isAcceptedGuess(word: string): boolean {
  const length = word.length;
  const allowed = length === 4 ? ALLOWED_4 : length === 5 ? ALLOWED_5 : ALLOWED_6;
  return (allowed as readonly string[]).includes(word);
}
