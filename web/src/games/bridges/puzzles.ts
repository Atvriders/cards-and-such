// Bridges (Hashiwokakero) puzzles
// Grid: null=empty, number=island with that count
// Islands connect via horizontal/vertical bridges (1 or 2 per pair)

export interface BridgesPuzzle {
  size: number;
  /** grid[r*size+c]: null=empty, number=island clue */
  grid: (number | null)[];
  /** Solution bridges: each entry [r1,c1,r2,c2,count] where count=1 or 2 */
  solution: [number, number, number, number, number][];
}

function mk(size: number, islands: [number, number, number][], bridges: [number, number, number, number, number][]): BridgesPuzzle {
  const grid: (number | null)[] = new Array(size * size).fill(null);
  for (const [r, c, n] of islands) grid[r * size + c] = n;
  return { size, grid, solution: bridges };
}

