// Akari (Light Up) puzzles
// Grid: 0=white, -1=black wall no number, 0-4=black wall with number
// W=wall(no clue), 0-4=wall with clue number

export interface AkariPuzzle {
  size: number;
  /** -1=black(no clue), 0..4=black with clue, null=white */
  grid: (number | null)[];
  solution: boolean[]; // true=bulb placed here
}

function w(size: number, walls: [number, number, number | null][], bulbs: [number, number][]): AkariPuzzle {
  const grid: (number | null)[] = new Array(size * size).fill(null);
  for (const [r, c, v] of walls) {
    grid[r * size + c] = v === null ? -1 : v;
  }
  const solution: boolean[] = new Array(size * size).fill(false);
  for (const [r, c] of bulbs) {
    solution[r * size + c] = true;
  }
  return { size, grid, solution };
}

